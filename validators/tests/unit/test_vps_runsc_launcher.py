def test_detach_relaunch_backs_up_stale_herdr_session_before_docker_run(
    tmp_path: Path,
) -> None:
    session_file = tmp_path / "seat-logs" / "xdg" / "config" / "herdr" / "session.json"
    session_file.parent.mkdir(parents=True)
    session_file.write_text('{"windows":[{"id":"w1","stale":true}]}\n', encoding="utf-8")
    codex_session = tmp_path / "codex-home" / "sessions" / "session.json"
    codex_session.parent.mkdir(parents=True)
    codex_session_text = '{"codex":"preserve-session-history"}\n'
    codex_session.write_text(codex_session_text, encoding="utf-8")

    result = run_live_wrapper_with_fake_docker(tmp_path, "--detach", "tui")

    assert result.returncode == 0, result.stderr
    assert not session_file.exists()
    assert codex_session.read_text(encoding="utf-8") == codex_session_text
    backups = list(session_file.parent.glob("session.json.prelaunch-backup.*"))
    assert len(backups) == 1
    assert backups[0].read_text(encoding="utf-8") == '{"windows":[{"id":"w1","stale":true}]}\n'
    assert (tmp_path / "contained-codex.toml").read_text(
        encoding="utf-8"
    ) == expected_contained_codex_config()
    assert "backed up stale herdr session" in result.stderr
    assert "container ce-vps-codex is ready" in result.stdout
    docker_log = (tmp_path / "docker-invocations.log").read_text(encoding="utf-8")
    commands = docker_log.splitlines()
    assert any(command == "rm -f ce-vps-codex" for command in commands)
    assert any(command.startswith("run -d --name ce-vps-codex ") for command in commands)
    assert any(command.startswith("exec ce-vps-codex test -S ") for command in commands)
    assert any(command.startswith("exec --env HERDR_SOCKET_PATH=") and " ce-vps-codex herdr pane list" in command for command in commands)
    assert "ancestor=" not in docker_log
    assert "pane-list={\"panes\":[{\"id\":\"w1:p1\"}]}" in docker_log
    # The relaunch must not replay stale herdr windows (e.g. w2/w3 from a stale
    # session.json). Match the herdr window-id token form ("wN:" pane ref or
    # '"id":"wN"' json) rather than a bare "wN" substring: the captured docker
    # argv embeds the tmp_path, which under pytest-xdist contains worker ids like
    # ".../popen-gw3/..." that would spuriously match a bare "w3".
    for stale_window in ("w2", "w3"):
        assert f"{stale_window}:" not in docker_log
        assert f'"id":"{stale_window}"' not in docker_log


