def run_wrapper(*args: str, **env_overrides: str | None) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env.pop("CE_LEDGER_ROOT", None)
    env.pop("CE_REVIEWER_AUTHORITY_REF", None)
    with tempfile.TemporaryDirectory(prefix="creator-engine-vps-runsc-test-") as runtime_dir:
        env.update(
            {
                "CE_VPS_DRY_RUN": "1",
                "CE_VPS_REPO": "/repo/creator-engine",
                "CE_VPS_CODEX_HOME": "/home/seat/.codex",
                "CE_VPS_CODEX_BIN": "/opt/codex/bin/codex",
                "CE_VPS_CLAUDE_BIN": "/opt/claude/bin/claude",
                "CE_VPS_CONTAINER_USER": "seat",
                "CE_VPS_SEAT_LOG_DIR": f"{runtime_dir}/seat-logs",
                "CE_VPS_UID": "1234",
                "CE_VPS_GID": "5678",
                "XDG_RUNTIME_DIR": runtime_dir,
                "TERM": "xterm-256color",
                "CLAUDE_CODE_OAUTH_TOKEN": "synthetic-secret-token-value",
            }
        )
        for key, value in env_overrides.items():
            if value is None:
                env.pop(key, None)
            else:
                env[key] = value
        return subprocess.run(
            ["bash", str(SCRIPT), "--dry-run", *args],
            cwd=REPO_ROOT,
            env=env,
            text=True,
            capture_output=True,
            check=False,
        )


def dry_run_argv(result: subprocess.CompletedProcess[str]) -> list[str]:
    assert result.returncode == 0, result.stderr
    return shlex.split(result.stdout)


def runsc_image_index(argv: list[str]) -> int:
    matches = [index for index, arg in enumerate(argv) if RUNSC_IMAGE_RE.fullmatch(arg)]
    assert len(matches) == 1, argv
    return matches[0]


def make_live_fake_docker(root: Path) -> Path:
    fake_bin = root / "bin"
    fake_bin.mkdir()
    docker = fake_bin / "docker"
    docker.write_text(
        "#!/bin/sh\n"
        "if [ -n \"${CE_TEST_DOCKER_LOG:-}\" ]; then\n"
        "  printf '%s\\n' \"$*\" >> \"${CE_TEST_DOCKER_LOG}\"\n"
        "fi\n"
        "if [ \"$1\" = \"info\" ]; then\n"
        "  printf '{\"runsc-gvproxy-ptrace\":{}}\\n'\n"
        "  exit 0\n"
        "fi\n"
        "if [ \"$1\" = \"run\" ]; then\n"
        "  if [ -e \"${CE_TEST_HERDR_SESSION_FILE}\" ]; then\n"
        "    printf 'stale herdr session was still present before docker run\\n' >&2\n"
        "    exit 97\n"
        "  fi\n"
        "  printf 'fake-container-id\\n'\n"
        "  exit 0\n"
        "fi\n"
        "if [ \"$1\" = \"exec\" ]; then\n"
        "  case \" $* \" in\n"
        "    *' pane list'*)\n"
        "      if [ -n \"${CE_TEST_DOCKER_LOG:-}\" ]; then\n"
        "        printf '%s\\n' 'pane-list={\"panes\":[{\"id\":\"w1:p1\"}]}' >> \"${CE_TEST_DOCKER_LOG}\"\n"
        "      fi\n"
        "      printf '{\"panes\":[{\"id\":\"w1:p1\"}]}\\n'\n"
        "      ;;\n"
        "  esac\n"
        "  exit 0\n"
        "fi\n"
        "printf 'unexpected docker invocation: %s\\n' \"$*\" >&2\n"
        "exit 99\n",
        encoding="utf-8",
    )
    docker.chmod(0o755)
    return fake_bin


def run_live_wrapper_with_fake_docker(
    root: Path, *args: str, **env_overrides: str
) -> subprocess.CompletedProcess[str]:
    fake_bin = make_live_fake_docker(root)
    repo = root / "repo"
    codex_home = root / "codex-home"
    codex_bin = root / "codex"
    seat_logs = root / "seat-logs"
    repo.mkdir(exist_ok=True)
    codex_home.mkdir(exist_ok=True)
    codex_bin.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    codex_bin.chmod(0o755)

    env = os.environ.copy()
    env.pop("CE_LEDGER_ROOT", None)
    env.pop("CE_REVIEWER_AUTHORITY_REF", None)
    env.update(
        {
            "CE_VPS_DRY_RUN": "0",
            "CE_VPS_REPO": str(repo),
            "CE_VPS_CODEX_HOME": str(codex_home),
            "CE_VPS_CODEX_BIN": str(codex_bin),
            "CE_VPS_CONTAINED_CODEX_CONFIG": str(root / "contained-codex.toml"),
            "CE_VPS_CONTAINER_USER": "seat",
            "CE_VPS_SEAT_LOG_DIR": str(seat_logs),
            "CE_VPS_UID": "1234",
            "CE_VPS_GID": "5678",
            "CE_TEST_HERDR_SESSION_FILE": str(
                seat_logs / "xdg" / "config" / "herdr" / "session.json"
            ),
            "CE_TEST_DOCKER_LOG": str(root / "docker-invocations.log"),
            "PATH": f"{fake_bin}{os.pathsep}{env.get('PATH', '')}",
            "TERM": "xterm-256color",
        }
    )
    env.update(env_overrides)
    return subprocess.run(
        ["bash", str(SCRIPT), *args],
        cwd=REPO_ROOT,
        env=env,
        text=True,
        capture_output=True,
        check=False,
    )


